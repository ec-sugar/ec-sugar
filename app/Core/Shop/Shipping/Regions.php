{
    /** @var array<string, list<string>> 地域 => 都道府県 */
    public const array ALL = [
        '北海道' => ['北海道'],
        '東北' => ['青森県', '岩手県', '宮城県', '秋田県', '山形県', '福島県'],
        '関東' => ['茨城県', '栃木県', '群馬県', '埼玉県', '千葉県', '東京都', '神奈川県', '山梨県'],
        '信越' => ['新潟県', '長野県'],
        '北陸' => ['富山県', '石川県', '福井県'],
        '東海' => ['岐阜県', '静岡県', '愛知県', '三重県'],
        '近畿' => ['滋賀県', '京都府', '大阪府', '兵庫県', '奈良県', '和歌山県'],
        '中国' => ['鳥取県', '島根県', '岡山県', '広島県', '山口県'],
        '四国' => ['徳島県', '香川県', '愛媛県', '高知県'],
        '九州' => ['福岡県', '佐賀県', '長崎県', '熊本県', '大分県', '宮崎県', '鹿児島県'],
        '沖縄' => ['沖縄県'],
    ];

    public const array PREFECTURES = [
        '北海道', '青森県', '岩手県', '宮城県', '秋田県', '山形県', '福島県', '茨城県', '栃木県', '群馬県', '埼玉県', '千葉県', '東京都', '神奈川県',
        '新潟県', '富山県', '石川県', '福井県', '山梨県', '長野県', '岐阜県', '静岡県', '愛知県', '三重県', '滋賀県', '京都府', '大阪府', '兵庫県',
        '奈良県', '和歌山県', '鳥取県', '島根県', '岡山県', '広島県', '山口県', '徳島県', '香川県', '愛媛県', '高知県', '福岡県', '佐賀県', '長崎県',
        '熊本県', '大分県', '宮崎県', '鹿児島県', '沖縄県',
    ];

    public static function known(string $prefecture): bool
    {
        return in_array($prefecture, self::PREFECTURES, true);
    }

    /**
     * 全部の都道府県を同じ額にした表
     *
     * @return array<string, int>
     */
    public static function flat(int $fee): array
    {
        return array_fill_keys(self::PREFECTURES, $fee);
    }
}
