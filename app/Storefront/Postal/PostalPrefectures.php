    public const string MISMATCH = '郵便番号と都道府県が一致しません。どちらかに誤りがないか確認してください。';

    /** @var array<string, list<string>>|null 上 3 桁 => 都道府県（初めて使う時に RANGES から作る） */
    private static ?array $index = null;

    /**
     * 郵便番号（7 桁の数字。ハイフンは無くてもよい）の上 3 桁でありうる都道府県。表に無い・形が違う番号は null（照らせない）
     *
     * @return list<string>|null
     */
    public static function candidates(string $postal): ?array
    {
        $digits = preg_replace('/\D/', '', $postal) ?? '';

        if (strlen($digits) !== 7) {
            return null;
        }

        return self::index()[substr($digits, 0, 3)] ?? null;
    }

    /**
     * 選んだ都道府県が郵便番号と合うか。照らせない番号（表に無い上 3 桁）は合うとみなす（新しい番号の注文を止めない）
     */
    public static function matches(string $postal, string $prefecture): bool
    {
        $candidates = self::candidates($postal);

        return $candidates === null || in_array($prefecture, $candidates, true);
    }

    /**
     * @return array<string, list<string>>
     */
    private static function index(): array
    {
        if (self::$index !== null) {
            return self::$index;
        }

        $index = [];

        foreach (self::RANGES as $prefecture => $ranges) {
            foreach (explode(',', $ranges) as $range) {
                [$from, $to] = array_pad(explode('-', $range, 2), 2, null);

                foreach (range((int) $from, (int) ($to ?? $from)) as $number) {
                    $index[sprintf('%03d', $number)][] = $prefecture;
                }
            }
        }

        return self::$index = $index;
    }
}
