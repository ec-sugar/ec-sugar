<?php

declare(strict_types=1);

/*
| 売るファイル（App「ダウンロード販売」など。ADR 0084）の上限。私たちがホストして貸すので、1 つの店・1 つの盗まれたログインが
| サーバーのディスクを使い切らないようにする（2026-11-04、運営の判断。ホストするなら制限は要る。写真の上限 config/media.php と同じ考え方）。
| 数えるのは置いたファイルの大きさの合計（上げる途中のファイルは、同時に上げられる数で抑える）
*/
return [
    // 1 つのファイルの上限（MB）。App はこれより小さくしかできない
    'max_file_mb' => (int) env('DOWNLOADS_MAX_FILE_MB', 500),
    // 店ごとの合計（MB）。超えるファイルは上げられない（使っていないファイルを消せば上げられる）
    'shop_quota_mb' => (int) env('DOWNLOADS_SHOP_QUOTA_MB', 10240),
    // 1 回に送る切れ端の大きさ（MB）。入口の nginx の上限（12m）と Cloudflare の 1 回の要求の上限（100MB）より小さく
    'chunk_mb' => 8,
    // 店ごとに同時に上げられるファイルの数（上げる途中のファイルがディスクを埋めないように）
    'uploads_at_once' => 3,
    // 上げる途中のファイルを捨てるまでの時間（時間）
    'upload_hours' => 24,
];
